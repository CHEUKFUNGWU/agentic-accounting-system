// Package money is the exact-decimal value type used by every money path.
//
// It wraps shopspring/decimal (ADR-0002 D4) and carries the Python-parity
// rules the migration depends on (ADR-0002 D3 golden fixtures):
//
//   - String reproduces Python str(Decimal) byte for byte, including
//     scientific forms ("1E+2", "1E-7"), preserved trailing zeros ("1.500")
//     and the sign of zero ("-0.00").
//   - Parse accepts the Python Decimal string grammar for finite values
//     (fixed and scientific forms, underscores between digits per PEP 515,
//     surrounding whitespace). The non-finite specials ("Infinity", "NaN")
//     are rejected: no money path in the frozen reference produces them.
//   - Add and Sub run under the reference default context: 28 significant
//     digits, ROUND_HALF_EVEN, with Python's zero-sign rules and the
//     zero-operand exponent rules of the decimal specification.
//   - Round is Python's quantize with an explicit rounding mode at every
//     call site; no global default is read anywhere.
//
// Money crosses JSON as a string (or a bare json.Number token); no float64
// ever touches a money value. Code outside this package must not import
// shopspring/decimal — internal/core/money/lint_test.go enforces it.
package money

import (
	"encoding/json"
	"errors"
	"fmt"
	"math/big"
	"strconv"
	"strings"
	"unicode"

	"github.com/shopspring/decimal"
)

// precision is the arithmetic context precision of the Python reference
// (decimal's default context).
const precision = 28

// RoundingMode mirrors the Python decimal rounding modes. Every rounding
// site names its mode explicitly (ADR-0002 D4).
type RoundingMode int8

const (
	RoundHalfEven RoundingMode = iota // Python ROUND_HALF_EVEN (context default)
	RoundHalfUp                       // Python ROUND_HALF_UP (ties away from zero)
	RoundDown                         // Python ROUND_DOWN (toward zero)
	RoundUp                           // Python ROUND_UP (away from zero)
	RoundCeiling                      // Python ROUND_CEILING
	RoundFloor                        // Python ROUND_FLOOR
)

// ParseMode maps a fixture/JSON mode name to its RoundingMode. The names are
// the fixture wire forms generated by tools/gen_fixtures.py.
func ParseMode(name string) (RoundingMode, error) {
	switch name {
	case "half_even":
		return RoundHalfEven, nil
	case "half_up":
		return RoundHalfUp, nil
	case "down":
		return RoundDown, nil
	case "up":
		return RoundUp, nil
	case "ceiling":
		return RoundCeiling, nil
	case "floor":
		return RoundFloor, nil
	default:
		return 0, fmt.Errorf("money: unknown rounding mode %q", name)
	}
}

var (
	// ErrInvalidParse rejects input outside the Python Decimal string grammar
	// for finite values.
	ErrInvalidParse = errors.New("money: not a finite Python Decimal string form")
	// ErrQuantize mirrors decimal.InvalidOperation from quantize when the
	// result coefficient would exceed the context precision.
	ErrQuantize = errors.New("money: quantize result exceeds context precision")
)

// Money is an exact decimal value: a coefficient, a base-ten exponent and
// the sign of zero. shopspring/decimal stores the coefficient and exponent
// (ADR-0002 D4); it drops the sign of zero, so negZero restores it.
type Money struct {
	d       decimal.Decimal
	negZero bool
}

func fromParts(coeff *big.Int, exp int32, neg bool) Money {
	if coeff.Sign() == 0 {
		return Money{d: decimal.NewFromBigInt(new(big.Int), exp), negZero: neg}
	}
	if neg {
		coeff = new(big.Int).Neg(coeff)
	}
	return Money{d: decimal.NewFromBigInt(coeff, exp)}
}

// isNeg reports the sign bit: true for negative values and negative zero.
func (m Money) isNeg() bool {
	if m.d.IsZero() {
		return m.negZero
	}
	return m.d.Coefficient().Sign() < 0
}

// Parse accepts the Python Decimal string grammar for finite values:
// optional sign, digits with at most one decimal point ("5", "5.", ".5",
// "1.500"), optional exponent and surrounding whitespace. Underscores are
// free-floating separators inside the numeric body — the C _decimal parser
// (libmpdec) strips them wherever they appear ("1_", "_1", "1__0" all parse;
// pinned by fixtures), which is laxer than PEP 515 and is what the frozen
// reference actually does. Exponent notation normalizes like Python:
// Decimal("1.5E+3") keeps its form until String renders it.
func Parse(s string) (Money, error) {
	body := strings.TrimFunc(s, unicode.IsSpace)
	if body == "" {
		return Money{}, ErrInvalidParse
	}
	neg := false
	switch body[0] {
	case '-':
		neg = true
		body = body[1:]
	case '+':
		body = body[1:]
	}
	body = strings.ReplaceAll(body, "_", "")
	expOffset, rest, err := splitExponent(body)
	if err != nil {
		return Money{}, err
	}
	intPart, fracPart, ok := splitMantissa(rest)
	if !ok {
		return Money{}, ErrInvalidParse
	}
	digits := intPart + fracPart
	exp := -int32(len(fracPart)) + expOffset
	digits = strings.TrimLeft(digits, "0")
	if digits == "" {
		return fromParts(new(big.Int), exp, neg), nil
	}
	coeff, ok := new(big.Int).SetString(digits, 10)
	if !ok {
		return Money{}, ErrInvalidParse
	}
	return fromParts(coeff, exp, neg), nil
}

// splitExponent strips a trailing [eE][+-]?\d+ group and returns its value.
func splitExponent(s string) (int32, string, error) {
	idx := strings.IndexAny(s, "eE")
	if idx < 0 {
		return 0, s, nil
	}
	expStr := s[idx+1:]
	mantissa := s[:idx]
	if expStr == "" {
		return 0, "", ErrInvalidParse
	}
	expNeg := false
	switch expStr[0] {
	case '-':
		expNeg = true
		expStr = expStr[1:]
	case '+':
		expStr = expStr[1:]
	}
	if !validDigits(expStr) {
		return 0, "", ErrInvalidParse
	}
	v, err := strconv.ParseInt(expStr, 10, 64)
	if err != nil {
		return 0, "", ErrInvalidParse
	}
	if expNeg {
		v = -v
	}
	if v < -1<<31 || v > 1<<31-1 {
		return 0, "", ErrInvalidParse
	}
	return int32(v), mantissa, nil
}

// splitMantissa validates the digits/dot part (underscores already stripped)
// and returns the integer and fraction digit runs.
func splitMantissa(s string) (string, string, bool) {
	if s == "" {
		return "", "", false
	}
	dot := strings.Count(s, ".")
	if dot > 1 {
		return "", "", false
	}
	intPart, fracPart, _ := strings.Cut(s, ".")
	if !validDigits(intPart) || !validDigits(fracPart) {
		return "", "", false
	}
	if intPart == "" && fracPart == "" {
		return "", "", false // a lone "." is invalid in Python too
	}
	return intPart, fracPart, true
}

// validDigits checks a plain digit run (possibly empty for the mantissa side
// of the dot, as in ".5" or "5.").
func validDigits(s string) bool {
	for i := 0; i < len(s); i++ {
		if s[i] < '0' || s[i] > '9' {
			return false
		}
	}
	return true
}

// String renders the value exactly as Python str(Decimal) does:
// fixed notation when the exponent is <= 0 and the adjusted exponent is
// >= -6, scientific notation ("d[.ddd]E±x") otherwise, trailing zeros and
// the sign of zero preserved.
func (m Money) String() string {
	coeff := m.d.Coefficient()
	neg := m.isNeg()
	digits := new(big.Int).Abs(coeff).String()
	exp := m.d.Exponent()
	var b strings.Builder
	if neg {
		b.WriteByte('-')
	}
	adjusted := exp + int32(len(digits)) - 1
	if exp <= 0 && adjusted >= -6 {
		if exp == 0 {
			b.WriteString(digits)
			return b.String()
		}
		point := len(digits) + int(exp)
		if point <= 0 {
			b.WriteString("0.")
			b.WriteString(strings.Repeat("0", -point))
			b.WriteString(digits)
			return b.String()
		}
		b.WriteString(digits[:point])
		b.WriteByte('.')
		b.WriteString(digits[point:])
		return b.String()
	}
	b.WriteString(digits[:1])
	if len(digits) > 1 {
		b.WriteByte('.')
		b.WriteString(digits[1:])
	}
	b.WriteByte('E')
	if adjusted >= 0 {
		b.WriteByte('+')
	}
	b.WriteString(strconv.FormatInt(int64(adjusted), 10))
	return b.String()
}

// Add returns m + o under the reference context: exact when the result fits
// 28 significant digits, otherwise rounded half-even. shopspring aligns both
// operands to the smaller exponent before summing — the decimal
// specification's ideal exponent, which also covers zero operands exactly as
// Python does ("0" + "1E+2" → "100"; "0.00" + "1.5" → "1.50"; pinned by
// fixtures). Zero results take Python's sign rules.
func (m Money) Add(o Money) Money {
	sum := m.d.Add(o.d)
	coeff := sum.Coefficient()
	exp := sum.Exponent()
	neg := coeff.Sign() < 0
	if neg {
		coeff.Neg(coeff)
	}
	capToContext(coeff, &exp)
	if coeff.Sign() == 0 {
		// Zero result: same-sign zero operands keep that sign; opposite-sign
		// cancellation always yields positive zero.
		neg = m.isNeg() && o.isNeg()
	}
	return fromParts(coeff, exp, neg)
}

// Sub returns m - o. Python defines subtraction as addition of the negation.
func (m Money) Sub(o Money) Money {
	return m.Add(o.Neg())
}

// Neg flips the sign bit, including the sign of zero (Python -Decimal).
func (m Money) Neg() Money {
	if m.d.IsZero() {
		return Money{d: m.d, negZero: !m.negZero}
	}
	coeff := m.d.Coefficient()
	return Money{d: decimal.NewFromBigInt(new(big.Int).Neg(coeff), m.d.Exponent())}
}

// capToContext rounds the absolute coefficient to `precision` significant
// digits, half-even, raising the exponent. Python's add does the same when a
// sum exceeds context precision.
func capToContext(coeff *big.Int, exp *int32) {
	digits := len(coeff.String())
	if digits <= precision {
		return
	}
	shift := digits - precision
	q := pow10(int64(shift))
	rem := new(big.Int)
	coeff.DivMod(coeff, q, rem)
	twice := new(big.Int).Lsh(rem, 1)
	if twice.Cmp(q) > 0 || (twice.Cmp(q) == 0 && coeff.Bit(0) == 1) {
		coeff.Add(coeff, big.NewInt(1))
	}
	// A rounding carry (…999 + 1 → 10^28) cascades through exact zeros.
	ten := big.NewInt(10)
	for len(coeff.String()) > precision {
		coeff.Div(coeff, ten)
		*exp++
	}
	*exp += int32(shift)
}

// Round is Python Decimal.quantize: coerce the exponent to -places, rounding
// the dropped digits with the explicit mode. It errors when the quantized
// coefficient would exceed context precision (decimal.InvalidOperation).
func (m Money) Round(places int32, mode RoundingMode) (Money, error) {
	target := -places
	cur := m.d.Exponent()
	coeff := new(big.Int).Abs(m.d.Coefficient())
	sign := m.isNeg()
	switch {
	case cur == target:
		if len(coeff.String()) > precision {
			return Money{}, ErrQuantize
		}
		return fromParts(coeff, target, sign), nil
	case cur > target:
		// Fewer decimals than the value carries: append exact zeros.
		coeff.Mul(coeff, pow10(int64(cur-target)))
		if len(coeff.String()) > precision {
			return Money{}, ErrQuantize
		}
		return fromParts(coeff, target, sign), nil
	default:
		// More decimals: round the dropped digits.
		q := pow10(int64(target - cur))
		keep, rem := new(big.Int).QuoRem(coeff, q, new(big.Int))
		if roundIncrement(rem, q, keep, mode, sign) {
			keep.Add(keep, big.NewInt(1))
		}
		if len(keep.String()) > precision {
			return Money{}, ErrQuantize
		}
		return fromParts(keep, target, sign), nil
	}
}

// roundIncrement decides whether the kept coefficient increments for the
// mode. sign is the operand's sign bit; zero results keep the operand's sign
// for every mode, matching the decimal specification.
func roundIncrement(rem, q, keep *big.Int, mode RoundingMode, neg bool) bool {
	if rem.Sign() == 0 {
		return false
	}
	twice := new(big.Int).Lsh(rem, 1)
	switch mode {
	case RoundDown:
		return false
	case RoundUp:
		return true
	case RoundCeiling:
		return !neg
	case RoundFloor:
		return neg
	case RoundHalfUp:
		return twice.Cmp(q) >= 0
	case RoundHalfEven:
		if twice.Cmp(q) > 0 {
			return true
		}
		if twice.Cmp(q) == 0 {
			return keep.Bit(0) == 1
		}
		return false
	default:
		return false
	}
}

func pow10(n int64) *big.Int {
	return new(big.Int).Exp(big.NewInt(10), big.NewInt(n), nil)
}

// IsZero reports whether the value is zero (either sign).
func (m Money) IsZero() bool { return m.d.IsZero() }

// IsNeg reports the sign bit: negative values and negative zero.
func (m Money) IsNeg() bool { return m.isNeg() }

// Cmp compares numerically like Python Decimal comparison; the sign of zero
// does not affect ordering.
func (m Money) Cmp(o Money) int { return m.d.Cmp(o.d) }

// Equal reports numeric equality (scale-insensitive, like Python ==).
func (m Money) Equal(o Money) bool { return m.Cmp(o) == 0 }

// MarshalJSON encodes Money as a JSON string — never a float.
func (m Money) MarshalJSON() ([]byte, error) {
	return json.Marshal(m.String())
}

// UnmarshalJSON accepts a JSON string (the normal wire form) or a bare
// number token (json.Number callers). Floats are never involved: the token
// text is parsed as a decimal string verbatim.
func (m *Money) UnmarshalJSON(b []byte) error {
	s := strings.TrimSpace(string(b))
	if s == "null" {
		*m = Money{}
		return nil
	}
	raw := s
	if s[0] == '"' {
		var quoted string
		if err := json.Unmarshal(b, &quoted); err != nil {
			return ErrInvalidParse
		}
		raw = quoted
	} else if strings.HasPrefix(raw, "-") || (raw[0] >= '0' && raw[0] <= '9') {
		// bare number token: keep as-is
	} else {
		return ErrInvalidParse
	}
	v, err := Parse(raw)
	if err != nil {
		return err
	}
	*m = v
	return nil
}
