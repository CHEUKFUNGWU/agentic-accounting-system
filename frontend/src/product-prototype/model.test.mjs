import { test } from 'node:test'
import assert from 'node:assert/strict'
import { approve, bankTransactions, closeBlockers, documentLines, initialState, isBalanced, lockPeriod, matchBank, profit, returnDocument, supplement, trialBalance } from './model.ts'

test('initial fixtures are independent, balanced and explicitly blocked', () => {
  const s = initialState()
  assert.equal(closeBlockers(s), 6)
  for (const e of s.entries) assert.equal(isBalanced(e.lines), true)
  for (const d of s.documents) assert.equal(isBalanced(documentLines(d)), true)
  assert.equal(trialBalance(s).reduce((sum, r) => sum + r.debit - r.credit, 0), 0)
  assert.equal(profit(s).net, 1380000)
})
test('approval requires acknowledgement and complete evidence', () => {
  const s = initialState()
  assert.equal(approve(s, 'DOC-1028', false), s)
  assert.equal(approve(s, 'DOC-1026', true), s)
  assert.equal(approve(s, 'unknown', true), s)
  const approved = approve(s, 'DOC-1028', true)
  assert.equal(approved.entries.length, 4)
  assert.equal(approved.documents[0].status, 'posted')
  assert.equal(approve(approved, 'DOC-1028', true), approved)
  assert.equal(s.entries.length, 3)
})
test('return requires a reason, remains blocked, and can be resubmitted', () => {
  const s = initialState()
  assert.equal(returnDocument(s, 'DOC-1027', '  '), s)
  const returned = returnDocument(s, 'DOC-1027', '补充期间说明')
  assert.equal(returned.documents[1].status, 'returned')
  assert.equal(closeBlockers(returned), closeBlockers(s))
  assert.equal(approve(returned, 'DOC-1027', true), returned)
  const resubmitted = supplement(returned, 'DOC-1027')
  assert.equal(resubmitted.documents[1].status, 'review')
  assert.equal(approve(resubmitted, 'DOC-1027', true).entries.length, 4)
})
test('posted documents update journal, trial balance and report', () => {
  const approved = approve(initialState(), 'DOC-1027', true)
  assert.equal(profit(approved).expenses, 548000)
  assert.equal(profit(approved).net, 1312000)
  assert.equal(trialBalance(approved).reduce((n, r) => n + r.balance, 0), 0)
  assert.equal(approved.entries.at(-1).documentId, 'DOC-1027')
})
test('bank matching is idempotent and never creates entries', () => {
  const s = initialState()
  const matched = matchBank(s, bankTransactions[0].id)
  assert.equal(matched.entries, s.entries)
  assert.equal(matched.matched.length, 1)
  assert.equal(matchBank(matched, bankTransactions[0].id), matched)
  assert.equal(matchBank(s, 'fake'), s)
})
test('close requires all prerequisites and locks all business writes', () => {
  const s = initialState()
  assert.equal(lockPeriod(s, true), s)
  let complete = supplement(s, 'DOC-1026')
  for (const doc of complete.documents) complete = approve(complete, doc.id, true)
  for (const tx of bankTransactions) complete = matchBank(complete, tx.id)
  assert.equal(closeBlockers(complete), 1)
  complete = { ...complete, agentFailure: false }
  assert.equal(closeBlockers(complete), 0)
  assert.equal(lockPeriod(complete, false), complete)
  const locked = lockPeriod(complete, true)
  assert.equal(locked.locked, true)
  assert.equal(supplement(locked, 'DOC-1026'), locked)
  assert.equal(approve(locked, 'DOC-1028', true), locked)
  assert.equal(returnDocument(locked, 'DOC-1027', 'edit'), locked)
  assert.equal(matchBank(locked, 'BK-031'), locked)
})
test('journal validation rejects unsafe or unbalanced values', () => {
  assert.equal(isBalanced([{ code: 'x', name: 'x', debit: 1, credit: 0 }, { code: 'y', name: 'y', debit: 0, credit: 2 }]), false)
  assert.equal(isBalanced([{ code: 'x', name: 'x', debit: .1, credit: 0 }, { code: 'y', name: 'y', debit: 0, credit: .1 }]), false)
  assert.equal(isBalanced([]), false)
})
